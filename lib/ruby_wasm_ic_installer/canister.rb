# ruby_wasm_ic_installer/canister.rb: the Installer's canister half, carried
# by an Application (packed under /app, so it is there before anything is
# installed) and required at the top of its app.rb. `ruby_wasm_ic_installer
# setup <app_dir>` writes that require and the Declarations it serves.
#
# Core Ruby and the builder's IC only (IC.caller, IC.refuse, IC::DATA_DIR):
# it loads on a `minimal` canister, so it names no Encoding constant and
# requires nothing.
#
# The layout it keeps (W29, Q7 to Q11):
#   /data/gems/<name>-<version>/...     one directory per gem version, complete
#   /data/gems/.partial/<name>-<version>/  a version still arriving
#   /data/setup.rb                      the setup file: its generation and the
#                                       load paths, required at boot
# A version arrives into .partial by install_put and is renamed into place by
# install_commit, which also writes the setup file, last, once every gem it
# names is complete. A new setup file takes effect at the next boot. A version
# is removed only by install_remove, and never while the running boot or the
# pending one names it. Every method is for the canister's controllers only.
module RubyWasmIcInstaller
  module Canister
    # A gem version's directory: a gem name, a dash, a version.
    NAME_VERSION = /\A[A-Za-z0-9][A-Za-z0-9_.\-]*-[0-9][A-Za-z0-9_.\-]*\z/
    SETUP_HEAD = "# generated by ruby_wasm_ic_installer: do not edit, it is rewritten by install_commit\n"
    GENERATION_LINE = /\A# generation: (\d+)$/

    class << self
      # The running generation (the setup file this boot loaded), or nil.
      attr_reader :running_generation

      def data_dir = @data_dir || IC::DATA_DIR
      attr_writer :data_dir

      def gems_dir = File.join(data_dir, "gems")
      def partial_dir = File.join(gems_dir, ".partial")
      def setup_file = File.join(data_dir, "setup.rb")

      # At boot: load the setup file if there is one. It calls #setup below.
      def boot!
        @running_generation = nil
        @running_paths = []
        load(setup_file) if File.file?(setup_file)
        self
      end

      # Called by the setup file: puts its load paths on $LOAD_PATH, after
      # /app (so a Carried library still shadows an installed one) and before
      # the Shipped library, in the lock's order.
      def setup(generation, load_paths)
        @running_generation = generation
        @running_paths = load_paths.map { |p| File.join(gems_dir, p) }
        app = $LOAD_PATH.rindex { |p| p == "/app" || p.start_with?("/app/") }
        $LOAD_PATH.insert(app ? app + 1 : 0, *(@running_paths - $LOAD_PATH))
        nil
      end

      # install_put: files into .partial/<name-version>/, each path
      # "<name-version>/<path inside the gem>".
      def put(files)
        controller!
        files.each do |f|
          nv, rest = split!(f[:path])
          full = File.join(partial_dir, nv, rest)
          mkdir_p(File.dirname(full))
          File.binwrite(full, f[:body])
        end
        "wrote #{files.size} files, #{files.sum { _1[:body].bytesize }} bytes"
      end

      # install_commit: rename each named .partial directory into place, then
      # write the setup file if one is given, whose every load path must be
      # inside a complete version.
      def commit(request)
        controller!
        done = request[:gems].map do |nv|
          name_version!(nv)
          from = File.join(partial_dir, nv)
          to = File.join(gems_dir, nv)
          IC.refuse("#{nv} has nothing in .partial to commit") unless File.directory?(from)
          IC.refuse("#{nv} is already installed") if File.exist?(to)
          File.rename(from, to)
          nv
        end
        msg = "committed #{done.size} gems"
        setup = request[:setup]
        return msg unless setup

        write_setup!(setup[:generation], setup[:load_paths])
        "#{msg}; wrote setup generation #{setup[:generation]}"
      end

      # install_remove: delete one complete version that neither the running
      # boot nor the pending setup file names, or a leftover in .partial.
      def remove(nv)
        controller!
        name_version!(nv)
        if File.directory?(File.join(partial_dir, nv)) && !File.exist?(File.join(gems_dir, nv))
          rm_r(File.join(partial_dir, nv))
          return "removed #{nv} from .partial"
        end
        dir = File.join(gems_dir, nv)
        IC.refuse("#{nv} is not installed") unless File.directory?(dir)
        IC.refuse("#{nv} is named by the running boot (generation #{running_generation})") if named?(running_names, nv)
        IC.refuse("#{nv} is named by the pending setup (generation #{pending_generation})") if named?(pending_names, nv)
        rm_r(dir)
        "removed #{nv}"
      end

      # installed: public, a query. What runs and what is waiting.
      def installed
        {
          running: running_generation,
          pending: pending_generation,
          gems: list(gems_dir),
          partial: list(partial_dir),
          load_paths: pending_paths,
          running_paths: (@running_paths || []).map { _1.delete_prefix("#{gems_dir}/") }
        }
      end

      def pending_generation
        return nil unless File.file?(setup_file)

        File.foreach(setup_file) { |l| return Regexp.last_match(1).to_i if l =~ GENERATION_LINE }
        nil
      end

      private

      def controller!
        IC.caller.controller? || IC.refuse("only a controller may install code")
      end

      def name_version!(nv)
        IC.refuse("not a gem version directory: #{nv.inspect}") unless nv.is_a?(String) && nv =~ NAME_VERSION
        nv
      end

      # "<name-version>/<rest>", with no absolute path, no "..", no "." and
      # no empty segment.
      def split!(path)
        IC.refuse("path must be relative: #{path}") if path.start_with?("/")
        parts = path.split("/", -1)
        IC.refuse("path must not hold . or .. or an empty segment: #{path}") if parts.any? { ["", ".", ".."].include?(_1) }
        IC.refuse("path must be <name-version>/<file>: #{path}") if parts.size < 2
        [name_version!(parts.first), parts.drop(1).join("/")]
      end

      def write_setup!(generation, load_paths)
        unless generation.is_a?(Integer) && generation > (pending_generation || 0) && generation > (running_generation || 0)
          IC.refuse("setup generation #{generation} must be above the pending (#{pending_generation.inspect}) " \
                    "and running (#{running_generation.inspect}) ones")
        end
        load_paths.each do |p|
          nv, = split!(p)
          IC.refuse("load path #{p} is not inside an installed gem") unless File.directory?(File.join(gems_dir, p)) &&
                                                                             File.directory?(File.join(gems_dir, nv))
        end
        body = SETUP_HEAD + "# generation: #{generation}\n" \
               "RubyWasmIcInstaller::Canister.setup(#{generation}, #{load_paths.map(&:to_s).inspect})\n"
        File.write(setup_file, body)
      end

      def pending_paths
        return [] unless File.file?(setup_file)

        line = File.foreach(setup_file).find { _1.start_with?("RubyWasmIcInstaller::Canister.setup(") }
        return [] unless line

        line.scan(/"((?:[^"\\]|\\.)*)"/).map(&:first)
      end

      def running_names = (@running_paths || []).map { |p| p.delete_prefix("#{gems_dir}/").split("/").first }
      def pending_names = pending_paths.map { _1.split("/").first }
      def named?(names, nv) = names.include?(nv)

      def list(dir)
        return [] unless File.directory?(dir)

        Dir.children(dir).reject { _1.start_with?(".") }.select { File.directory?(File.join(dir, _1)) }.sort
      end

      def mkdir_p(dir)
        return if File.directory?(dir)

        mkdir_p(File.dirname(dir))
        Dir.mkdir(dir)
      end

      def rm_r(path)
        if File.directory?(path) && !File.symlink?(path)
          Dir.children(path).each { rm_r(File.join(path, _1)) }
          Dir.rmdir(path)
        else
          File.delete(path)
        end
      end
    end
  end
end

# The Declarations `setup` writes into ic-interface.rb are served by these.
def install_put(files) = RubyWasmIcInstaller::Canister.put(files)
def install_commit(request) = RubyWasmIcInstaller::Canister.commit(request)
def install_remove(name_version) = RubyWasmIcInstaller::Canister.remove(name_version)
def installed = RubyWasmIcInstaller::Canister.installed

RubyWasmIcInstaller::Canister.boot! if defined?(IC::DATA_DIR)
